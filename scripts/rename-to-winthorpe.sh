remaining=$(grep -rIli 'helmor' \
  --exclude-dir=node_modules --exclude-dir=.git --exclude-dir=target \
  --exclude-dir=dist --exclude-dir=.bundle-cache --exclude-dir=.next \
  --exclude=CHANGELOG.md --exclude='calm-models-dance.md' \
  --exclude='neat-branches-divide.md' --exclude=NOTICE \
  --exclude='*.lock' --exclude='rename-to-winthorpe.sh' \
