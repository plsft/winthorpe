echo "  1. Review with: git diff --stat"
echo "  2. Lockfiles will regenerate on next install/build"
echo "  3. Snapshot files will regenerate on next 'cargo test'"
echo "  4. Brand image content still helmor-branded — replace with Winthorpe artwork later"
